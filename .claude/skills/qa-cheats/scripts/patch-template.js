const PKG = "__PKG__"; // replaced at inject time
const CMD_FILE = "/storage/emulated/0/Android/data/" + PKG + "/files/qa_cmd.txt";
const LOG_FILE = "/storage/emulated/0/Android/data/" + PKG + "/files/qa.log";
function log(s) { try { const f = new File(LOG_FILE, "a"); f.write(Date.now() + " " + s + "\n"); f.flush(); f.close(); } catch (e) {} }
function readCmd() { try { return File.readAllText(CMD_FILE).trim(); } catch (e) { return ""; } }
function clearCmd() { try { const f = new File(CMD_FILE, "w"); f.write(""); f.flush(); f.close(); } catch (e) {} }

// Queue il2cpp calls and drain them on the Unity thread (hook a per-frame method you confirmed).
