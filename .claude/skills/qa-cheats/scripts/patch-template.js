function pump() {
  const cmd = readCmd();
  if (cmd) {
    clearCmd();
    const [op, arg] = cmd.split(/\s+/);
    log("cmd " + cmd);
    if (op === "coin") enqueue(() => callVoid(RVA.addGold));
    else if (op === "life") enqueue(() => callVoid(RVA.infiniteLife, ptr(LIFE_SECONDS)));
    else if (op === "level") enqueue(() => callVoid(RVA.setLevel, ptr(parseInt(arg || "1", 10))));
    else if (op === "win") enqueue(() => callVoid(RVA.winLevel));
  }
  while (Q.length) { try { Q.shift()(); } catch (e) { log("drain err " + e); } }
}

